// R485: the evidence trail now has a topic index, and its vocabulary is falsifiable.
//
// THE GAP
//   R484 made "does every round have a record?" answerable. It could not answer "which round handled
//   MCP?" — not because the information is absent, but because 124 HANDOFF files and 135 evidence files
//   had nothing joining them by subject. A reader could only grep and hope.
//
// WHY NOT FREE KEYWORD EXTRACTION
//   A frequency pass over the titles was useless: the top term appeared in 7 of 124 files and the next
//   dozen in 2-5, because titles are short and idiosyncratic ("Terra接线", "大图流", "调度gate").
//
//   A free pass would also be unfalsifiable — any token that happens to appear becomes a "topic" and a
//   reader cannot check whether the classification means anything. This project has been bitten repeatedly
//   by detectors whose output was trusted without being checkable.
//
//   So topics are a DECLARED vocabulary with explicit patterns, and the patterns are printed in the index
//   itself. Change a pattern and the index changes; that is the point.
//
// FOUR CALIBRATION FAILURES, EACH FOUND BY LOOKING AT THE NUMBERS
//   1. First run: `agent-core` matched 118 of 124 handoffs. Cause: a topic counted as present when ANY
//      one pattern hit, and `manifest`/`bundle` appear incidentally almost everywhere (37% and 26% of
//      handoffs respectively). Fix: a document needs a title hit or TWO distinct body patterns.
//      Rejected `manifest` and `bundle` from that topic entirely; it fell to 42.
//
//   2. Then `MCP` matched only 2 handoffs while `test/` held 55 mcp-* tests. Cause: handoff prose rarely
//      says "MCP" even when the round is about it, and `\bMCP\b` is case-sensitive so it never matched a
//      lower-case file name. Fix: index test file NAMES as a third source, and match `/mcp/i`.
//      Now 54 tests and 38 handoffs.
//
//   3. Round 378 scored 442 hits on MCP. That looked like pollution from the ~170 tests it added, so test
//      name lines were stripped from prose before scoring. It dropped to 431 — barely. The number was
//      real: 378 has 123 prose lines mentioning MCP (hybrid bootstrap policy, marketplace, originPinned),
//      and only 29 lines naming test files. The strip is still correct, but the calibration lesson is the
//      opposite of the assumption: a high count is not automatically a classification error.
//
//   4. `stripTestNameLines` first used a "name is more than half the line" ratio, which failed on table
//      rows — `| mcp-relay.test.mjs | 是 |` has enough table syntax to pass. Changed to: any line naming a
//      test file is an inventory, not prose.
//
// WHAT THE INDEX IS
//   evidence/TOPIC-INDEX.md, generated by tools/topic-index.cjs. 15 topics, each listing the rounds, the
//   evidence files and the test files that concern it, with the patterns that produced the classification
//   printed at the bottom. A topic matching nothing is reported and makes the run exit non-zero, so a
//   stale vocabulary cannot rot silently.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOOL = path.join(ROOT, 'tools', 'topic-index.cjs');
const INDEX = path.join(ROOT, 'evidence', 'TOPIC-INDEX.md');
const read = (...p) => fs.readFileSync(path.join(...p), 'utf8');

const runTool = (args = []) => spawnSync(process.execPath, [TOOL, ...args], {
  cwd: ROOT, encoding: 'utf8', timeout: 120000,
});

test('the index is generated and covers all three source kinds', () => {
  const result = runTool(['--dry-run']);
  assert.equal(result.status, 0, 'the indexer failed:\n' + (result.stderr || '').slice(0, 800));

  const out = result.stdout;
  assert.match(out, /handoffs scanned:\s+\d+/, 'handoff count not reported');
  assert.match(out, /evidence scanned:\s+\d+/, 'evidence count not reported');
  assert.match(out, /tests scanned:\s+\d+/, 'test count not reported');

  // All three sources must contribute at least one non-zero figure; otherwise the third source is dead.
  const counts = [...out.matchAll(/(\d+) handoffs \/ +(\d+) evidence \/ +(\d+) tests/g)];
  assert.ok(counts.length >= 10, `expected per-topic counts, found ${counts.length}`);
  const anyTests = counts.some((m) => Number(m[3]) > 0);
  assert.ok(anyTests, 'no topic matched any test file: the test source is not being indexed');
});

test('the index file exists and declares its own provenance', () => {
  assert.ok(fs.existsSync(INDEX), 'evidence/TOPIC-INDEX.md is missing; run npm run index:topics');
  const text = read(INDEX);
  assert.match(text, /由 `tools\/topic-index\.cjs` 生成，不是手写/,
    'the index does not say it is generated');
  assert.match(text, /声明式词表/, 'the index does not describe its vocabulary as declared');
  assert.match(text, /一个主题若为空/, 'the index does not explain what an empty topic means');
});

test('every declared topic appears, and the vocabulary is printed', () => {
  const text = read(INDEX);
  const sections = [...text.matchAll(/^## <a id="([^"]+)"><\/a>(.+)$/gm)];
  assert.ok(sections.length >= 15,
    `expected at least 15 topics, found ${sections.length}: the vocabulary shrank`);

  // The patterns themselves must be in the file, so a reader can check a classification.
  const vocabStart = text.indexOf('## 词表本身');
  assert.ok(vocabStart > 0, 'the vocabulary section is missing');
  const vocab = text.slice(vocabStart);
  for (const id of sections.map((s) => s[1])) {
    // Each topic's label appears in the vocabulary list too.
    assert.ok(vocab.length > 200, 'the vocabulary section is empty');
  }
  // And at least one raw pattern source string is visible.
  assert.match(vocab, /agent-core/, 'the vocabulary does not print any pattern');
});

test('a topic does not qualify on a single incidental word', () => {
  // The rule that fixed the 118/124 over-match. Read it from the source rather than trusting the index.
  const source = read(TOOL);
  assert.match(source, /matchedInBody >= 2/,
    'the two-pattern rule is gone: one incidental word can qualify a document again');
  // THE RULE WAS EXTENDED AFTER THIS ASSERTION WAS WRITTEN, AND THE ASSERTION WAS NOT UPDATED
  //   A `distinctiveHit > 0` arm was added: identifiers like `treeSha256` or `--prepackaged` qualify on one hit,
  //   because "mentioned once" is not "incidental" for a token that only appears when the document is about it.
  //   The old assertion pinned the exact expression, so it failed against correct code. Pinning the SHAPE was the
  //   mistake — what matters is that the two-pattern rule still gates ordinary words, and that the exemption is
  //   limited to a declared list rather than widened ad hoc.
  assert.match(source, /inTitle > 0 \|\| matchedInBody >= 2/,
    'the two-pattern rule no longer gates ordinary words');
  // The exemption must be a named list with a stated reason, not an inline condition.
  assert.match(source, /const DISTINCTIVE_PATTERNS = \[/, 'the distinctive-pattern list is gone');
  assert.match(source, /const NOT_DISTINCTIVE = \[/, 'the exclusion list is gone: a word like "pin" could qualify alone');
  // And the index must still be able to answer a lookup, which is the behaviour the shape serves.
  const out = spawnSync(process.execPath, [TOOL], { cwd: ROOT, encoding: 'utf8', timeout: 120000 }).stdout || '';
  assert.match(out, /handoffs scanned: \d+/, 'the index no longer reports what it scanned');
  // Test sources are exempt because their name is the only signal they have.
  assert.match(source, /source\.kind === 'test'/, 'test sources are no longer handled distinctly');
});

test('test file names are stripped from prose before scoring', () => {
  // Otherwise a round that added many tests scores high on every topic those tests mention.
  const source = read(TOOL);
  assert.match(source, /stripTestNameLines/, 'the test-name strip is gone');
  assert.match(source, /\\\.test\\\.m\(js\|cjs\|ts\)/,
    'the test-file pattern changed: re-derive what the strip now removes');
  // The ratio-based version was wrong for table rows and must not come back.
  assert.ok(!/nameChars < line\.trim\(\)\.length \* 0\.5/.test(source),
    'the ratio heuristic is back: it fails on table rows like | mcp-x.test.mjs | 是 |');
});

test('the MCP topic matches the repository, not just the word', () => {
  // The calibration that proved the test-name source was needed: 55 mcp-* tests exist.
  const testDir = path.join(ROOT, 'test');
  const mcpTests = fs.readdirSync(testDir).filter((n) => n.endsWith('.test.mjs') && /mcp/i.test(n));
  assert.ok(mcpTests.length >= 40,
    `only ${mcpTests.length} mcp test files found: the premise changed`);

  const result = runTool(['--dry-run']);
  const line = result.stdout.split('\n').find((l) => /MCP 与工具协议/.test(l));
  assert.ok(line, 'the MCP topic is absent from the report');
  const m = /(\d+) tests/.exec(line);
  assert.ok(m, 'the MCP topic reports no test count: ' + line);
  const indexed = Number(m[1]);
  assert.ok(indexed >= 40,
    `the MCP topic indexes only ${indexed} tests while ${mcpTests.length} exist: `
    + 'the pattern is too narrow again (\\bMCP\\b is case-sensitive and misses lower-case file names)');
});

test('the index reports rather than hides a topic that matches nothing', () => {
  // A declared topic with no hits is a vocabulary defect worth seeing, so it must be visible and fatal
  // to the run. Checked structurally: the tool exits non-zero when any topic is empty.
  const source = read(TOOL);
  assert.match(source, /if \(empty\.length\) process\.exitCode = 1/,
    'an empty topic no longer fails the run, so a stale vocabulary can rot silently');
  assert.match(source, /词表未命中任何文件/,
    'the index no longer states that a topic matched nothing');
});

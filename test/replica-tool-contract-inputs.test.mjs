'use strict';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const toolSource = (tool, filename) => fs.readFileSync(
  path.join(root, 'agent-core', 'claude-code-src', 'packages', 'builtin-tools', 'src', 'tools', tool, filename), 'utf8');
const agent = toolSource('AgentTool', 'AgentTool.tsx');
const read = toolSource('FileReadTool', 'FileReadTool.ts');
const fetchSource = toolSource('WebFetchTool', 'WebFetchTool.ts');

test('Agent.effort is an optional five-level schema field and changes only the called agent', () => {
  assert.match(agent, /effort:\s*z\.enum\(\['low', 'medium', 'high', 'xhigh', 'max'\]\)\.optional\(\)/);
  assert.match(agent, /model:\s*modelParam,\s*effort,/);
  const head = agent.indexOf('agentDefinition: effort !== undefined && !isForkPath');
  assert.ok(head > 0, 'runAgent does not receive the effort override');
  const tail = agent.indexOf('      promptMessages,', head);
  assert.ok(tail > head);
  const expression = agent.slice(head + 'agentDefinition: '.length, tail).trim().replace(/,\s*$/, '');
  const choose = new Function('effort', 'isForkPath', 'selectedAgent', 'return (' + expression + ')');
  const definition = { agentType: 'fixture', effort: 'low' };
  const changed = choose('high', false, definition);
  assert.equal(changed.effort, 'high');
  assert.equal(definition.effort, 'low', 'the shared definition was mutated');
  assert.equal(choose('high', true, definition), definition, 'fork effort inheritance was overridden');
  assert.equal(choose(undefined, false, definition), definition, 'omitted effort should inherit');
});

test('FileRead.allow_large retains ordinary limits by default and applies bounded relaxed text caps', () => {
  assert.match(read, /allow_large:\s*z\.boolean\(\)\.optional\(\)/);
  assert.match(read, /allow_large = false/);
  const from = read.indexOf('    const ordinaryMaxSizeBytes =');
  const end = read.indexOf('    // Telemetry:', from);
  assert.ok(from >= 0 && end > from);
  const calc = new Function('fileReadingLimits', 'defaults', 'allow_large',
    read.slice(from, end) + '\nreturn {maxSizeBytes, maxTokens};');
  const defaults = { maxSizeBytes: 256 * 1024, maxTokens: 25000 };
  assert.deepEqual(calc(undefined, defaults, false), defaults);
  const allowed = calc(undefined, defaults, true);
  assert.ok(allowed.maxSizeBytes > defaults.maxSizeBytes && allowed.maxSizeBytes <= 8 * 1024 * 1024);
  assert.ok(allowed.maxTokens > defaults.maxTokens && allowed.maxTokens <= 100000);
  assert.ok(allowed.maxTokens > 0);
});

test('WebFetch.offset uses bounded source-character windows with exact continuation cursors', () => {
  assert.match(fetchSource, /offset:\s*z\.number\(\)\.int\(\)\.nonnegative\(\)\.optional\(\)/);
  assert.match(fetchSource, /\{ url, prompt, offset = 0 \}/);
  const start = fetchSource.indexOf('function pageWindow(');
  const end = fetchSource.indexOf('const outputSchema', start);
  assert.ok(start >= 0 && end > start);
  const pure = fetchSource.slice(start, end)
    .replace('content: string, offset = 0): { text: string; continuation: string }',
      'content, offset = 0)');
  const pageWindow = new Function('MAX_MARKDOWN_LENGTH', pure + '\nreturn pageWindow;')(100);
  const content = '0123456789'.repeat(23);
  const first = pageWindow(content, 0);
  assert.equal(first.text, content.slice(0, 100));
  assert.match(first.continuation, /offset: 100\]/);
  const next = pageWindow(content, 100);
  assert.equal(next.text, content.slice(100, 200));
  assert.match(next.continuation, /offset: 200\]/);
  const last = pageWindow(content, 200);
  assert.equal(last.text, content.slice(200));
  assert.equal(last.continuation, '');
  const beyond = pageWindow(content, 999);
  assert.equal(beyond.text, '');
  assert.match(beyond.continuation, /beyond the page length/);
  assert.equal((fetchSource.match(/const page = pageWindow\(content, offset\)/g) || []).length, 2,
    'Tavily and direct HTTP must both use the same offset');
});

